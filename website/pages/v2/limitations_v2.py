st.subheader("一、与策略1.0共同的局限性")

st.markdown("""
**① 幸存者偏差（Survivorship Bias）— 当前最高优先级风险**

当前回测标的池基于 2024 年末仍在 S&P 500 / S&P 400 成分股中的股票，
未包含历史上已退市、破产或被踢出指数的公司。
这会系统性高估 CAGR，历史研究表明偏差幅度通常在 **20%–50%**。

解决方案（未来）：使用 Compustat 或 CRSP 的逐日历史成分股数据重建点对点标的池。

**② 市值过滤数据不完整**

Yahoo Finance 不提供历史时间点市值数据，市值过滤在回测中未完全执行，
依赖 S&P 成分股名单作为隐性市值门槛（存在滞后性）。

**③ 大资金规模的摩擦成本**

市场冲击成本、流动性约束、策略拥挤效应随管理规模增大而显著上升。
当前回测未对 $1,000 万以上的资金规模做成本调整。
""")

st.subheader("二、策略2.0特有的局限性与已知风险")

st.markdown("""
**④ 横盘收敛过滤的参数敏感性未知**

80 日窗口和 25% 阈值是设计时选择的参数，尚未经过样本外验证。
若参数敏感性测试显示绩效对这两个参数高度敏感，则存在过拟合风险。
**这是策略2.0回测后首要验证项。**

**⑤ 信号频率大幅降低的潜在风险**

横盘收敛条件会大幅减少入场信号数量（相比策略1.0）。
信号减少会导致：
- 回测交易笔数降低，统计显著性下降
- 年内可能出现较长的空仓期（无横盘突破机会）
- 在某些市场环境下（如垂直上涨的 AI 牛市）可能完全缺席

**⑥ 结构止损的历史验证缺失**

`structure_stop = lowest(low, 20) × 0.995` 是新引入的止损机制，
与 ATR 止损的协同作用尚未经过完整历史验证。
在特定市场环境下（如快速大幅跳水），结构止损可能实际执行价格与预期偏差较大。

**⑦ 单层移动止盈的均值回归风险**

使用 `highest(high, 20) - 2×ATR` 作为单层移动止盈，在震荡市中可能比策略1.0的
3×ATR 更容易被噪音触发，导致在趋势仍在延续时过早退出。
这需要通过回测的持仓时长和交易频率数据来验证。

**⑧ touch_count 条件被暂时省略**

条件3（触顶次数 ≥ 2）已在初版 Baseline 中省略，以便先验证横盘收敛本身的增量价值。
后续可能根据回测结果决定是否引入，存在一定的迭代实验风险（多重检验）。
""")

