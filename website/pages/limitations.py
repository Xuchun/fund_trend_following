# ── Limitation 4: Volume filter for ETFs ─────────────────────────────────────
st.subheader("4. 成交量过滤对 ETF 适用性较弱")
st.markdown("""
**问题：** 成交量放大对个股意味着机构买入确认，但 ETF 成交量由市场做市机制驱动，量能含义不同。

- 个股成交量放大 → 机构资金流入的有效信号
- ETF 成交量放大 → 可能仅反映套利机制或市场整体波动，未必代表趋势共识

若 ETF 占标的池较大比例，该过滤器可能过度拒绝 ETF 的有效趋势信号，导致回测低估 ETF 趋势跟踪的真实收益。

**改善方向：** 对个股和 ETF 分别设置成交量过滤参数，或对 ETF 完全禁用成交量过滤。

---
""")

# ── Limitation 5: Regime filter design ───────────────────────────────────────
st.subheader("5. 市场环境过滤器局限性")
st.markdown("""
**问题 1：震荡市场中的频繁切换（Whipsaw）**

SPY 在横盘整理时可能反复穿越 200 日均线，导致策略1.0频繁在「允许开仓」和「停止开仓」之间切换。
回测中每次切换均按信号精确执行，但真实环境中频繁切换会带来心理压力，
且实际入场/错过的时机与回测假设存在偏差。

**改善方向：** 引入缓冲带，减少噪声切换：
- 牛市确认：SPY > SMA × 1.02（高于均线 2%）才切换为牛市
- 熊市确认：SPY < SMA × 0.98（低于均线 2%）才切换为熊市

---

**问题 2：用美国大盘指数过滤所有资产类别**

策略1.0标的包含债券 ETF、商品 ETF、行业 ETF 等，它们与 SPY 的相关性各异。
当 SPY 处于熊市（低于 200 日均线）时，债券 ETF 或商品 ETF 可能正处于强趋势中，
用 SPY 作为统一过滤器会错过这些非相关资产的趋势机会。

**改善方向：** 改用各标的自身价格与均线的关系做个股过滤，而非依赖单一 SPY 信号。

---
""")

