# ── No lookahead bias ─────────────────────────────────────────────────────────
st.subheader("2. 防前视偏差（No Look-Ahead Bias）")
st.markdown("""
本回测严格遵循**信息隔离**原则，确保每一步只使用当时可得的历史信息：

| 操作 | 时间点 |
|------|--------|
| 突破信号计算 | `adj_close[t] > max(adj_high[t-N : t-1])`，今日调整收盘价需超过过去 N 日盘中最高价峰值，t 日收盘后计算 |
| 成交量确认 | 比较 t 日成交量 vs mean(volume[t-60:t-1])（shift=1，无前视偏差） |
| 突破强度计算 | `adj_close[t] / max(adj_high[t-N : t-1])`，分子为今日调整收盘价，分母为过去 N 日（不含今日）盘中最高价峰值，均基于 t 日收盘后已知数据 |
| 止损/移动止盈更新 | t 日收盘后 |
| ATR 计算 | 使用 Wilder 指数平滑，无未来数据 |
| Gap 过滤（入场） | t+1 开盘价已知后判断：若开盘跳空幅度 `\|open[t+1] − close[t]\| / close[t] > 2.5%`，拒绝该笔开仓；仅使用 t+1 日已知信息，无前视偏差 |
| 交易执行 | t+1 日开盘价（含滑点、佣金） |
| 仓位规模计算 | 使用 t 日 ATR（已知量），止损距离以 t+1 实际成交价重新锚定 |

""")

st.markdown("---")

# ── Signal execution order ────────────────────────────────────────────────────
st.subheader("3. 每日信号执行顺序")
st.markdown("""
每个交易日收盘后，引擎按固定顺序处理信号，确保因果关系严格成立：

```
t 日收盘后（信号生成阶段）
  ① 更新持仓状态：highest_high ← max(highest_high, adj_high[t])
                   trail_stop 向上棘轮（只升不降）
  ② 判断平仓信号（按优先级）：
     - 止损     — adj_low[t]   < stop_loss  → t+1 开盘执行
     - 移动止盈 — adj_close[t] < trail_stop → t+1 开盘执行
     （注：若今日创新高导致 trail_stop 上移，且收盘价低于新 trail_stop，
      则同日棘轮并触发出场，t+1 开盘平仓）
  ③ 生成新的开仓信号（突破扫描）

t+1 日开盘（执行阶段）
  ④ 先执行平仓指令（释放资金和风险额度）
  ⑤ 再执行开仓指令（基于更新后的 NAV 和风险敞口）
```

**关键规则：同一标的在同一时点不会同时开仓与平仓。** 平仓指令先于开仓指令执行，后续信号的相关性计算与组合热度检查均基于平仓后的最新状态。
""")

st.markdown("---")

# ── Integer shares ────────────────────────────────────────────────────────────
st.subheader("4. 开仓数量取整（四舍五入）")
st.markdown("""
策略按照风险比例法计算每笔交易的理论开仓股数，计算结果通常带有小数部分。
由于现实中股票只能以**整数股**买卖，回测与模拟交易均按**四舍五入**原则取整：

$$
\\text{理论股数} = \\frac{\\text{NAV} \\times \\text{risk\\_per\\_trade}}{\\text{entry\\_price} - \\text{stop\\_price}}
$$

$$
\\text{实际股数} = \\text{round}(\\text{理论股数})
\\quad\\Rightarrow\\quad
\\text{小数部分} \\geq 0.5 \\text{ 进一，}< 0.5 \\text{ 舍去}
$$

**示例：**

| 情景 | NAV | 风险比例 | 止损距离 | 理论股数 | 实际股数 |
|------|-----|---------|---------|---------|---------|
| 正常取整（进一） | $200,000 | 1% | $3.20 | 62.5 股 | **63 股** |
| 正常取整（舍去） | $200,000 | 1% | $3.10 | 64.5 股 → 实为 64.51 | **65 股** |
| 触及仓位上限 | $200,000 | 1% | $0.80 | 2,500 股（超 5% 上限）| 按 5% 上限截断后取整 |

**取整对风险的实际影响：**
- 每笔交易因取整产生的风险偏差约为 ±0.5 股 × 止损距离
- 以 $200K 账户、止损距离 $3 为例，偏差约 ±$1.50，占 NAV 的 **±0.00075%**，可忽略不计
- 回测中计算方式与模拟交易完全一致，不存在实现偏差

**回测中的实现方式：**
```python
import math
shares = math.floor(raw_shares + 0.5)   # 四舍五入，等价于 round-half-up
```
""")

