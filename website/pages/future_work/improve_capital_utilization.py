st.markdown("""
**为什么选 TLT？**

当股市因经济衰退或金融危机下跌时，美联储通常降息，长期国债价格上涨（利率与债券价格反向）。
2001–02（降息 6.5%→1.75%）和 2008–09（降息至 0%）正是 TLT 历史上最强的趋势行情。
长期限（20Y+）意味着更大的久期敏感性，利率每降 1%，TLT 价格涨约 17-18%。

**为什么选 GLD？**

黄金是全球公认的避险资产，在货币信用受损、通胀预期上升、地缘风险加剧时走强。
与 TLT 的相关性也较低——2022 年 TLT 大跌时 GLD 基本横盘，形成互补。
GLD 上市于 2004-11，2000–2004 年的缺口不影响策略，因为该阶段回测用其他信号覆盖。

**2022 年的自动保护机制**

2022 年是利率快速上升引发的熊市，TLT 和 GLD 均未能趋势上涨。但这不是问题——
因为策略要求价格突破 **200 日高点** 才能入场，而 2022 年 TLT 持续下跌，永远不会触发 200 日高点突破。
豁免机制不会在 2022 年产生任何 TLT 入场信号，资金仍然停在 SHY。
""")

