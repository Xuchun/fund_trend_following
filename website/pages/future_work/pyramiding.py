# ── 一、核心思路 ──────────────────────────────────────────────────────────────
st.subheader("一、核心思路")

st.markdown("""
趋势跟踪的利润高度集中在少数大赢家。以策略1.0为例，TOP 20 标的贡献了绝大多数利润，
而约 65% 的交易以止损出场。

**当前做法（固定仓位）的矛盾：**

- 入场时用全仓（5% NAV 上限），无论趋势最终走多远
- 大多数交易在入场后不久就止损，每次止损都损失全仓的风险
- 大赢家和小亏家一开始用同样大的仓位，但结局完全不同

**金字塔的逻辑：先用小仓试探，只有趋势被验证后才追加。**

入场时用较小的仓位，如果价格确实按预期方向运动（上涨到 +1R、+2R），
才逐步追加，让真正的大趋势获得更多资本支持。
失败的突破（很快触发止损）只损失小仓位，大的资本投入留给了真正有效的趋势。
""")

st.info("💡 **核心原理**：用市场行为来决定仓位大小——只有已经证明自己的趋势，才值得更大的押注。")

st.markdown("---")

# ── 二、对 CAGR 和最大回撤的影响机制 ────────────────────────────────────────
st.subheader("二、对年化绩效和最大回撤的影响机制")

col1, col2 = st.columns(2)

with col1:
    st.markdown("#### 为什么可能提高 CAGR")
    st.markdown("""
**放大右尾效应**

趋势跟踪靠少数大赢家驱动，金字塔让这些大赢家获得更多资本：

- 固定仓位：+15R 的大赢家从始至终只有 5% NAV
- 金字塔：在 +1R、+2R 各追加后，+15R 的赢家可能持有 10–12% NAV

最终收益差距可达 **2–2.5 倍**。

**资本更有效地流向赢家**

当前策略对所有持仓一视同仁。金字塔让资本自动向表现好的仓位集中，
接近了"顺势加注"的理想状态。
""")

with col2:
    st.markdown("#### 为什么可能降低最大回撤")
    st.markdown("""
**初始仓位更小，假突破损失更少**

最大回撤主要来自两个来源：
1. 市场压力期大量持仓同时亏损
2. 初始入场后很快被止损出场

金字塔将初始仓位缩小到目标的 40–50%。
当市场转差时，只有初始小仓被止损，
追加的仓位（在 +1R、+2R 时才建立）还未形成，
组合的总暴露更低。

**追加仓位自带移动止损保护**

每次追加时，整个持仓的止损线都会上移，
早期追加的盈利已经足以覆盖后期追加的潜在亏损。
""")

st.markdown("---")

# ── 三、具体实现方案 ────────────────────────────────────────────────────────
st.subheader("三、具体实现方案（基于策略1.0框架）")

st.markdown("#### 方案：固定梯级追加")

st.markdown("""
将一笔完整仓位分成三批买入，每批触发条件不同：

| 批次 | 触发条件 | 仓位比例 | 止损设置 |
|------|---------|---------|---------|
| **初始入场** | 价格突破 200 日高点（当前触发条件不变） | 目标仓位的 **40%** | 入场价 − 2×ATR（同现在） |
| **第一次追加** | 持仓盈利达到 **+1R**（即价格上涨 = 初始止损距离） | 目标仓位的 **35%** | 上移至追加价 − 2×ATR |
| **第二次追加** | 持仓盈利达到 **+2R** | 目标仓位的 **25%** | 上移至追加价 − 2×ATR |

目标仓位上限（5% NAV）在全部追加完成后才达到，初始入场只用 2% NAV。
""")

st.markdown("""
**数值示例：**

假设某股票入场价 $100，止损 $95（止损距离 5%，1R = 5%），目标仓位 5% NAV（$500,000）：

| 批次 | 触发价 | 买入金额 | 累计持仓 | 当前止损 | 整体盈亏平衡点 |
|------|-------|---------|---------|---------|--------------|
| 初始入场 | $100 | $200,000（2% NAV）| $200,000 | $95 | $100 |
| +1R 追加 | $105 | $175,000（1.75% NAV）| $375,000 | $100 | $102.7 |
| +2R 追加 | $110 | $125,000（1.25% NAV）| $500,000 | $105 | $105.6 |

**关键点：** 第二次追加后，止损上移至 $105，整体盈亏平衡价 $105.6——即使趋势反转，
最差情况下整个持仓已**微盈**。
""")

st.markdown("---")

# ── 四、与固定仓位的对比 ────────────────────────────────────────────────────
st.subheader("四、与固定仓位的盈亏对比")

st.markdown("""
假设 100 笔交易，5% NAV 目标仓位，2×ATR 止损（止损距离 5%），分两种情景：

**情景 A：假突破（65% 的交易，很快止损）**

| 方式 | 入场仓位 | 损失（占 NAV）|
|------|---------|------------|
| 固定仓位 | 5% NAV | −0.25% NAV/笔 |
| 金字塔 | 2% NAV（只有初始批） | −0.10% NAV/笔 |

假突破损失降低 **60%**。

**情景 B：大赢家（+10R，约 5% 的交易）**

| 方式 | 最终仓位 | 收益（占 NAV）|
|------|---------|------------|
| 固定仓位 | 5% NAV | +2.5% NAV/笔 |
| 金字塔 | 5% NAV（全部追加完成）| +3.1% NAV/笔（均价更低，每股赚得更多）|

大赢家收益提升约 **+24%**（因为追加仓位的入场价更高，但平均成本摊薄效应使整体利润率改善）。

> **净效果**：损失端下降，盈利端上升——这正是"CAGR 提升 + 最大回撤降低"同时发生的理论基础。
""")

st.markdown("---")

# ── 五、历史先例 ────────────────────────────────────────────────────────────
st.subheader("五、历史先例")

st.markdown("""
金字塔加仓是趋势跟踪领域的经典技术，有大量实盘验证：

| 交易员 / 系统 | 金字塔方式 |
|-------------|-----------|
| **海龟交易法则**（Richard Dennis） | 每上涨 ½N（½ATR）追加一个 Unit，最多追加 4 次 |
| **Ed Seykota** | 顺势追加，强调"永远不要减小盈利仓位" |
| **AHL / Man Investments** | 系统化追加，仓位随趋势强度动态调整 |
| **Jerry Parker（Chesapeake Capital）**| 分批建仓，只对盈利持仓追加 |

海龟规则的具体实现：入场后每上涨 ½N 追加，止损随每次追加上移 ½N，
最大同一品种持仓 = 4 Units，对应策略1.0中约等于 4 次追加。
""")

st.markdown("---")

# ── 六、主要风险和挑战 ──────────────────────────────────────────────────────
st.subheader("六、主要风险和挑战")

st.markdown("""
金字塔并非没有代价：

**① 趋势回调时亏损放大**

如果在追加后趋势立刻反转，总仓位已经最大化，
且追加批次的入场价更高，止损触发时损失比固定仓位更大。
这种"V 形反转"对金字塔最不利。

**② 执行复杂度上升**

需要追踪每个持仓的盈利状态、计算追加价格、更新止损线、管理多个批次的成本基础。
代码量和 bug 风险均增加。

**③ 成交价不利**

追加时价格已经上涨，平均成本高于固定仓位入场价。
对于最终未能继续上涨的趋势，金字塔的每股成本更高。

**④ 需要 Walk-Forward 验证**

金字塔的触发参数（+1R、+2R 追加？还是 +0.5R、+1R？追加比例如何分配？）
存在过拟合风险，必须通过 Walk-Forward 在样本外验证，不能单靠回测优化。
""")

st.warning("""
⚠️ **关键风险：** 金字塔在单边顺畅大趋势中表现优异，但在震荡市（频繁假突破）
或急速反转行情中可能显著增加损失。实施前必须做全面的参数敏感性分析和 Walk-Forward 验证。
""")

st.markdown("---")

